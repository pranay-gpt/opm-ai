"""Agentic self-heal: propose fixes for lint issues with confidence weighting.

This is the top-level user-facing feature for the v2 linter. Given a
`.DATA` deck (text or path), the self-heal module:

1. Parses and validates the deck with the v2 linter.
2. For each lint issue, runs the corresponding fix proposal (or asks
   an LLM if no mechanical proposal is registered).
3. Verifies each proposed patched deck against the OPM Flow oracle.
4. Ranks proposals by confidence (a blend of historical calibration
   rate, oracle verdict on the patched deck, and rule severity).
5. Returns a ranked list of FixProposal objects the user can choose
   to apply.

Design philosophy
-----------------

Self-heal is **conservative**: it never auto-applies. The user (or a
downstream agent) reviews each proposal. Self-heal is a sorter, not
an executor.

Calibration-based confidence: the rule-specific historical success
rate from calibration_report.json is the dominant signal. A proposal
for a rule that historically fails 50% of the time is downweighted
regardless of how good it looks in isolation.

Oracle-verified proposals are flagged "verified". A proposal that
keeps the deck passing Flow is verified=True. A proposal that
breaks the deck is verified=False and gets a heavy downweight.

LLM proposals: for issues that don't have a mechanical proposal
function (no rule in `fix_proposals.propose_fix` registry), the
self-heal module can ask an LLM. The LLM is constrained to return a
patched deck that the linter re-parses successfully; this gives us a
free syntax check. LLM proposals are flagged `llm_proposed=True` and
carry the same oracle verification flow.

API
---

```python
from opm_ai.linter.v2.self_heal import SelfHealResult, self_heal_deck

result = self_heal_deck(
    text=deck_text,
    source_file=Path("/path/to/x.DATA"),
    calibration_report=report_dict,  # or None to skip calibration weighting
    use_llm=True,  # ask LLM for issues without mechanical proposals
    oracle_cfg=OracleConfig(),
)
for proposal in result.proposals:
    print(proposal.rule_code, proposal.confidence, proposal.verified, proposal.description)
```
"""

from __future__ import annotations

import json
